#!/usr/bin/env sh
# Print the Homebrew cask for kit <version>, reading sha256s from a goreleaser-style checksums.txt.
# Usage: sh scripts/cask.sh <version> <checksums.txt>
set -eu

version="${1:?usage: cask.sh <version> <checksums.txt>}"
sums="${2:?usage: cask.sh <version> <checksums.txt>}"
base='https://github.com/FacileStudio/kit/releases/download/v#{version}'

sha() {
  hash="$(awk -v f="kit_${version}_$1.tar.gz" '$2 == f { print $1 }' "$sums")"
  [ -n "$hash" ] || { echo "cask.sh: no checksum for kit_${version}_$1.tar.gz" >&2; exit 1; }
  printf '%s' "$hash"
}

darwin_arm64="$(sha darwin_arm64)"
darwin_amd64="$(sha darwin_amd64)"
linux_arm64="$(sha linux_arm64)"
linux_amd64="$(sha linux_amd64)"

cat <<CASK
# This file was generated by FacileStudio/kit release.yml. DO NOT EDIT.
cask "kit" do
  version "${version}"

  on_macos do
    on_arm do
      sha256 "${darwin_arm64}"
      url "${base}/kit_#{version}_darwin_arm64.tar.gz"
    end
    on_intel do
      sha256 "${darwin_amd64}"
      url "${base}/kit_#{version}_darwin_amd64.tar.gz"
    end
  end
  on_linux do
    on_arm do
      sha256 "${linux_arm64}"
      url "${base}/kit_#{version}_linux_arm64.tar.gz"
    end
    on_intel do
      sha256 "${linux_amd64}"
      url "${base}/kit_#{version}_linux_amd64.tar.gz"
    end
  end

  name "kit"
  desc "Keep one list of Facile tools, Flathub apps and Nix packages, and make the machine match it"
  homepage "https://github.com/FacileStudio/kit"

  livecheck do
    skip "Auto-generated on release."
  end

  binary "kit"

  postflight do
    if system_command("/usr/bin/xattr", args: ["-h"]).exit_status == 0
      system_command "/usr/bin/xattr", args: ["-dr", "com.apple.quarantine", "#{staged_path}/kit"]
    end
  end

  zap :not_required
end
CASK
